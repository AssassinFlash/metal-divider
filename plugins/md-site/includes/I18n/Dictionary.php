	/**
	 * Retrieves localized UI text for a key.
	 *
	 * @param string      $key  Dictionary key.
	 * @param string|null $lang Target canonical language code, or null for current.
	 */
	public static function text( string $key, ?string $lang = null ): string {
		$target = null !== $lang ? Languages::from_wpml( $lang ) : Languages::current();
		if ( ! in_array( $target, Languages::ALL, true ) ) {
			$target = Languages::SOURCE;
		}

		if ( isset( self::TRANSLATIONS[ $target ][ $key ] ) ) {
			return self::TRANSLATIONS[ $target ][ $key ];
		}

		if ( isset( self::TRANSLATIONS[ Languages::SOURCE ][ $key ] ) ) {
			return self::TRANSLATIONS[ Languages::SOURCE ][ $key ];
		}

		return $key;
	}

	/**
	 * Retrieves chrome configuration strings for search/copy components.
	 *
	 * @param string|null $lang Target canonical language code, or null for current.
	 * @return array{noResults: string, kindPattern: string, kindPage: string, kindArticle: string, copied: string, copyFailed: string, copyEmailSuccess: string, copyEmailFallback: string, viewAllResults: string, clearSearch: string, closeLabel: string, selectLanguage: string}
	 */
	public static function chrome_config( ?string $lang = null ): array {
		$target = null !== $lang ? Languages::from_wpml( $lang ) : Languages::current();
		if ( ! in_array( $target, Languages::ALL, true ) ) {
			$target = Languages::SOURCE;
		}

		return self::CHROME_CONFIG[ $target ];
	}
