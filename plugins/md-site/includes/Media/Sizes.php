<?php
/**
 * The square crops the catalog cards draw.
 *
 * @package MetalDivider\Site
 */

declare( strict_types = 1 );

namespace MetalDivider\Site\Media;

/**
 * Registers the 1:1 sides the catalog card needs, and nothing else.
 *
 * The card's media box is `aspect-ratio: 1/1` at 338 CSS pixels
 * (`pattern-grid.css`), so a 1:1 source is what it actually draws. Until this
 * registration existed the card asked for the pattern's featured image as
 * WordPress had sized it — a 480x960 portrait at the top of its ladder — and
 * `object-fit: cover` then threw away more than half of every download.
 * Measured on the shop face at DPR 1: 163 KB for the tall file against 44 KB
 * for the square the site already held at 300x300.
 *
 * Two rungs, because one cannot serve both densities at a 338px box:
 * 338 CSS pixels needs 338 physical at DPR 1 and 676 at DPR 2. The 400 side
 * covers the first with a little headroom; the 800 side covers the second.
 * `$crop = true` is load-bearing — a soft proportion crop would produce
 * 400x800 from a portrait source and put the card back where it started.
 *
 * Sizes are registered rather than generated by the media pipeline
 * (`tools/media`) on purpose: WordPress already owns the attachment metadata
 * and `wp media regenerate --only-missing` fills in whatever is absent, so
 * the corpus stays WooCommerce's (§2 Woo-unique-source ruling) instead of
 * growing a second index of what exists.
 */
final class Sizes {

	/**
	 * The 1:1 side that covers the card box at DPR 1.
	 */
	public const CARD = 'md-card-square';

	/**
	 * The 1:1 side that covers the card box at DPR 2.
	 */
	public const CARD_2X = 'md-card-square-2x';

	/**
	 * The registered sides, name => [ width, height ].
	 *
	 * @return array<string, array{0: int<0, max>, 1: int<0, max>}> The sides.
	 */
	public static function definitions(): array {
		return array(
			self::CARD    => array( 400, 400 ),
			self::CARD_2X => array( 800, 800 ),
		);
	}

	/**
	 * Registers the sides with WordPress.
	 *
	 * `after_setup_theme` is the hook the handbook names for `add_image_size`:
	 * registering on `init` works for display but runs after the media
	 * screens have already read the list.
	 */
	public function register(): void {
		add_action( 'after_setup_theme', array( $this, 'add_sizes' ) );
	}

	/**
	 * Adds every registered side.
	 */
	public function add_sizes(): void {
		foreach ( self::definitions() as $name => $side ) {
			add_image_size( $name, $side[0], $side[1], true );
		}
	}
}
